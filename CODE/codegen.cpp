#include "codegen.h"
#include <fstream>
#include <iostream>

void CodeGenerator::generate(const PolicyConstraints& c, const std::string& outputFile) {
    std::ofstream out(outputFile);
    if (!out.is_open()) {
        std::cerr << "Failed to open " << outputFile << " for writing generated code.\n";
        return;
    }

    out << "// --- AUTO-GENERATED TARGET CODE ---\n";
    out << "// Generated by the Policy Compiler\n\n";
    out << "#include <iostream>\n";
    out << "#include <string>\n";
    out << "#include <vector>\n";
    out << "#include <cctype>\n";
    out << "#include <cmath>\n";
    out << "\n";
    out << "struct ValidationResult {\n";
    out << "    bool isValid;\n";
    out << "    std::vector<std::string> errors;\n";
    out << "    double entropyScore;\n";
    out << "};\n\n";

    out << "class CompiledPolicyValidator {\n";
    out << "private:\n";
    out << "    std::string password;\n\n";
    out << "    int calculatePoolSize(int uppers, int lowers, int digits, int specials) {\n";
    out << "        int pool = 0;\n";
    out << "        if (uppers > 0) pool += 26;\n";
    out << "        if (lowers > 0) pool += 26;\n";
    out << "        if (digits > 0) pool += 10;\n";
    out << "        if (specials > 0) pool += 32;\n";
    out << "        return pool;\n";
    out << "    }\n\n";
    out << "public:\n";
    out << "    CompiledPolicyValidator(const std::string& pwd) : password(pwd) {}\n\n";

    out << "    ValidationResult validate() {\n";
    out << "        ValidationResult result;\n";
    out << "        result.isValid = true;\n\n";

    out << "        int upperCount = 0, lowerCount = 0, digitCount = 0, specialCount = 0, spaceCount = 0;\n";
    out << "        for (char ch : password) {\n";
    out << "            if (std::isupper(ch)) upperCount++;\n";
    out << "            else if (std::islower(ch)) lowerCount++;\n";
    out << "            else if (std::isdigit(ch)) digitCount++;\n";
    out << "            else if (std::isspace(ch)) spaceCount++;\n";
    out << "            else specialCount++;\n";
    out << "        }\n\n";

    out << "        int pool = calculatePoolSize(upperCount, lowerCount, digitCount, specialCount);\n";
    out << "        if (pool > 0) {\n";
    out << "             result.entropyScore = password.length() * (std::log(pool) / std::log(2));\n";
    out << "        } else {\n";
    out << "             result.entropyScore = 0;\n";
    out << "        }\n\n";

    out << "        // --- COMPILED CONSTRAINTS INJECTION ---\n";
    if (c.minLength != -1) {
        out << "        if (password.length() < " << c.minLength << ") {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Password is too short. Minimum length is " << c.minLength << ".\");\n";
        out << "        }\n";
    }

    if (c.maxLength != -1) {
        out << "        if (password.length() > " << c.maxLength << ") {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Password is too long. Maximum length is " << c.maxLength << ".\");\n";
        out << "        }\n";
    }

    if (c.requireUpper == 1) {
        out << "        if (upperCount == 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Missing uppercase letter (A-Z).\");\n";
        out << "        }\n";
    } else if (c.requireUpper == 0) {
        out << "        if (upperCount > 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Uppercase letter (A-Z) is forbidden.\");\n";
        out << "        }\n";
    }

    if (c.requireLower == 1) {
        out << "        if (lowerCount == 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Missing lowercase letter (a-z).\");\n";
        out << "        }\n";
    } else if (c.requireLower == 0) {
        out << "        if (lowerCount > 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Lowercase letter (a-z) is forbidden.\");\n";
        out << "        }\n";
    }

    if (c.requireDigit == 1) {
        out << "        if (digitCount == 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Missing numeric digit (0-9).\");\n";
        out << "        }\n";
    } else if (c.requireDigit == 0) {
        out << "        if (digitCount > 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Numeric digit (0-9) is forbidden.\");\n";
        out << "        }\n";
    }

    if (c.requireSpecial == 1) {
        out << "        if (specialCount == 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Missing special character (!@#...).\");\n";
        out << "        }\n";
    } else if (c.requireSpecial == 0) {
        out << "        if (specialCount > 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Special character (!@#...) is forbidden.\");\n";
        out << "        }\n";
    }

    if (c.noSpaces == 1) {
        out << "        if (spaceCount > 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Password contains illegal whitespace characters.\");\n";
        out << "        }\n";
    } else if (c.noSpaces == 0) {
        out << "        if (spaceCount == 0) {\n";
        out << "            result.isValid = false;\n";
        out << "            result.errors.push_back(\"[REJECTED] Missing required space character.\");\n";
        out << "        }\n";
    }
    out << "        // --------------------------------------\n\n";

    out << "        return result;\n";
    out << "    }\n";
    out << "};\n\n";

    out << "int main() {\n";
    out << "    std::string inputPwd;\n";
    out << "    std::cout << \"========================================\\n\";\n";
    out << "    std::cout << \"  Standalone Target Policy Evaluator\\n\";\n";
    out << "    std::cout << \"========================================\\n\";\n";
    out << "    std::cout << \"Enter a password to validate: \";\n";
    out << "    std::getline(std::cin, inputPwd);\n\n";
    
    out << "    CompiledPolicyValidator validator(inputPwd);\n";
    out << "    ValidationResult res = validator.validate();\n\n";
    
    out << "    if (res.isValid) {\n";
    out << "        std::cout << \"\\n✅ STATUS: VALID\\n\";\n";
    out << "    } else {\n";
    out << "        std::cout << \"\\n❌ STATUS: INVALID\\n\";\n";
    out << "        std::cout << \"\\n-- Error Log --\\n\";\n";
    out << "        for (const auto& err : res.errors) {\n";
    out << "             std::cout << \"* \" << err << \"\\n\";\n";
    out << "        }\n";
    out << "    }\n";
    out << "    std::cout << \"\\n-- Metrics --\\n\";\n";
    out << "    std::cout << \"Calculated Entropy: \" << res.entropyScore << \" bits\\n\";\n";
    out << "    if (res.entropyScore > 80.0) std::cout << \"Strength: VERY STRONG\\n\";\n";
    out << "    else if (res.entropyScore > 60.0) std::cout << \"Strength: STRONG\\n\";\n";
    out << "    else if (res.entropyScore > 40.0) std::cout << \"Strength: MODERATE\\n\";\n";
    out << "    else std::cout << \"Strength: WEAK\\n\";\n";

    out << "    return 0;\n";
    out << "}\n";

    out.close();
}
